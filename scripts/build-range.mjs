const check = process.argv.includes('--check');
let stale = false;
for (const L of Object.keys(copy)) {
  const file = join(root, copy[L].file);
  const html = render(L);
  if (check) {
    let current = '';
    try { current = readFileSync(file, 'utf8'); } catch {}
    if (current !== html) { stale = true; console.error(`${copy[L].file} is out of date. Run: node scripts/build-range.mjs`); }
  } else {
    writeFileSync(file, html);
    console.log(`wrote ${copy[L].file}`);
  }
}
if (stale) process.exit(1);
