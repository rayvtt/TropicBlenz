// Builds the bilingual range landing page from scripts/range/content.mjs:
//   range.html     English
//   range-vi.html  Vietnamese
// Usage: node scripts/build-range.mjs          write both pages
//        node scripts/build-range.mjs --check  fail if the committed pages are out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { BRAND, SITE_URL, fruits, blends, copy } from './range/content.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const byId = Object.fromEntries(fruits.map((f) => [f.id, f]));

// Escape plain-text values that go into attributes.
const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const pad = (n) => String(n).padStart(2, '0');
const otherLang = (lang) => (lang === 'en' ? 'vi' : 'en');

function fruitCard(f, i, L, t) {
  const alt = otherLang(L);
  return `
            <li class="fruit" style="--tint:${f.tint};--on-tint:${f.ink}">
              <div class="fruit__field" aria-hidden="true">
                <span class="fruit__num">${pad(i + 1)}</span>
                <span class="fruit__alt" lang="${alt}">${f.name[alt]}</span>
              </div>
              <div class="fruit__body">
                <p class="fruit__photo"><span class="tag">${t.range.photoTag}</span></p>
                <h4 class="fruit__name">${f.name[L]}</h4>
                <p class="fruit__notes">${f.notes[L]}</p>
                <p class="fruit__label">${t.range.useLabel}</p>
                <ul class="chips">${f.uses[L].map((u) => `<li>${u}</li>`).join('')}</ul>
              </div>
            </li>`;
}

function blendCard(b, i, L, t) {
  return `
            <li class="blend" style="--tint:${b.tint}">
              <p class="blend__top"><span class="blend__num">${pad(i + 1)}</span><span class="tag tag--light">${t.range.blendsTag}</span></p>
              <h4 class="blend__name">${b.name}</h4>
              <p class="blend__label">${t.range.inLabel}</p>
              <ul class="blend__fruits">${b.fruits.map((id) => `<li><span class="dot" style="--dot:${byId[id].tint}" aria-hidden="true"></span>${byId[id].name[L]}</li>`).join('')}</ul>
              <p class="blend__notes">${b.notes[L]}</p>
              <p class="blend__label">${t.range.useLabel}</p>
              <ul class="chips chips--light">${b.uses[L].map((u) => `<li>${u}</li>`).join('')}</ul>
            </li>`;
}

function recipe(r, t) {
  const media = r.img
    ? `
              <figure class="idea__media">
                <img src="assets/img/${r.img}" alt="${attr(r.alt)}" loading="lazy" width="${r.w}" height="${r.h}">
                <figcaption class="photo-credit">${t.recipes.credit}</figcaption>
              </figure>`
    : '';
  return `
            <article class="idea${r.img ? ' idea--photo' : ''}">${media}
              <div class="idea__body">
                <p class="idea__meta">${r.meta}</p>
                <h3 class="idea__title">${r.title}</h3>
                <p>${r.text}</p>
              </div>
            </article>`;
}

